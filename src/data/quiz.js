export function getQuestionsByLevel(level) {
  if (!level || level === 'All') return quizQuestions
  return quizQuestions.filter(q => q.level === level)
}

export function getRandomQuestions(count = 10, level = null) {
  const pool = level && level !== 'All' ? getQuestionsByLevel(level) : quizQuestions
  const shuffled = [...pool].sort(() => Math.random() - 0.5)
  return shuffled.slice(0, Math.min(count, shuffled.length))
}
